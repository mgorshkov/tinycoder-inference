// Fused IQ3_XXS gate+up GEMV: one launch, one Q8_1 activation quantization,
// four rows per block, one warp per row.
extern "C" __global__ void gemvIQ3XXSFusedGUF32PlainCuda1(
    const void *__restrict__ vg, const void *__restrict__ vu,
    const void *__restrict__ vy, float *__restrict__ gout,
    float *__restrict__ uout, const int ncols_x, const int nrows_x,
    const int stride_col_y) {
  constexpr int qi = QI3_XXS;
  constexpr int vdr = VDR_IQ3_XXS_Q8_1_GEMV;
  const int row = blockIdx.x * 4 + threadIdx.y;
  if (row >= nrows_x) return;
  const int lane = threadIdx.x;
  const int blocks_per_row = ncols_x / QK_K;
  constexpr int blocks_per_iter = vdr * WARP_SIZE / qi;
  const block_q8_1 *y = static_cast<const block_q8_1 *>(vy);
  float sg = 0.0f, su = 0.0f;
  for (int kbx = lane / (qi / vdr); kbx < blocks_per_row;
       kbx += blocks_per_iter) {
    const int kby = kbx * (QK_K / QK8_1);
    const int kqs = vdr * (lane % (qi / vdr));
    sg += vec_dot_iq3_xxs_q8_1(vg, &y[kby], row * blocks_per_row + kbx, kqs);
    su += vec_dot_iq3_xxs_q8_1(vu, &y[kby], row * blocks_per_row + kbx, kqs);
  }
#pragma unroll
  for (int off = 16; off > 0; off >>= 1) {
    sg += __shfl_down_sync(0xffffffffu, sg, off);
    su += __shfl_down_sync(0xffffffffu, su, off);
  }
  if (lane == 0) {
    gout[row] = (sg / (1.0f + expf(-sg))) * su;
    uout[row] = su;
  }
}

